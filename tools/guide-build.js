#!/usr/bin/env node
// Study Guide content tool.
//   node tools/guide-build.js import <full-guide.md>   split the complete guide into guide/intro.md + guide/l01.md … l24.md
//   node tools/guide-build.js index                    rebuild guide/index.js (overview data) after editing a lesson file
//   node tools/guide-build.js check                    exit 1 if guide/index.js is out of date (used by the tests)
// Lesson files are the source of truth: edit guide/lNN.md, then run "index".
const fs = require('fs'), path = require('path');
const G = require('../guide-md.js');
const ROOT = path.join(__dirname, '..'), DIR = path.join(ROOT, 'guide');
const pad = n => String(n).padStart(2, '0');

function steps() {
  // Stable Grammar Lab destinations; independent of the removed static Grammar Book.
  return Object.fromEntries(Array.from({ length: 25 }, (_, i) => [i + 1, 'grammar-lab.html?s=' + (i + 1)]));
}
function importFull(file) {
  const md = fs.readFileSync(file, 'utf8').replace(/\r\n?/g, '\n');
  const marks = [...md.matchAll(/^## (A1\.[12]) · Lektion (\d+)\s*$/gm)];
  if (marks.length !== 24) throw new Error(`expected 24 lessons, found ${marks.length}`);
  fs.mkdirSync(DIR, { recursive: true });
  // the guide's own title page (before Lektion 1) – without the doc title repeated in front of lesson 1
  const intro = md.slice(0, marks[0].index).replace(/\n# Deutsch im echten Leben\s*$/, '').trimEnd() + '\n';
  fs.writeFileSync(path.join(DIR, 'intro.md'), intro);
  marks.forEach((m, k) => {
    const end = k + 1 < marks.length ? marks[k + 1].index : md.length;
    let body = md.slice(m.index, end).replace(/\n# Deutsch im echten Leben\s*$/, '').trimEnd() + '\n';
    fs.writeFileSync(path.join(DIR, `l${pad(+m[2])}.md`), body);
  });
  console.log('imported 24 lessons + intro into guide/');
}
function buildIndex() {
  const st = steps();
  const lessons = []; for (let n = 1; n <= 24; n++) {
    const s = G.summary(fs.readFileSync(path.join(DIR, `l${pad(n)}.md`), 'utf8'), st);
    if (s.n !== n) throw new Error(`guide/l${pad(n)}.md says Lektion ${s.n}`);
    if (s.unmatched.length) throw new Error(`guide/l${pad(n)}.md: headings without a Study Guide part: ${s.unmatched.join(', ')}`);
    delete s.unmatched; lessons.push(s);
  }
  return '// Generated by tools/guide-build.js from guide/*.md — do not edit by hand; run "node tools/guide-build.js index".\n' +
    'window.GUIDE_STEPS = ' + JSON.stringify(st) + ';\n' +
    'window.GUIDE_INDEX = ' + JSON.stringify(lessons) + ';\n';
}
const [cmd, arg] = process.argv.slice(2);
if (cmd === 'import') { importFull(arg); fs.writeFileSync(path.join(DIR, 'index.js'), buildIndex()); console.log('wrote guide/index.js') }
else if (cmd === 'index') { fs.writeFileSync(path.join(DIR, 'index.js'), buildIndex()); console.log('wrote guide/index.js') }
else if (cmd === 'check') { const ok = fs.readFileSync(path.join(DIR, 'index.js'), 'utf8') === buildIndex(); if (!ok) { console.error('guide/index.js is out of date: run node tools/guide-build.js index'); process.exit(1) } console.log('guide/index.js up to date') }
else { console.log('usage: guide-build.js import <file.md> | index | check'); process.exit(2) }
